/**
 * Generates icon credits from installed package metadata and preserves license notices.
 * Scans src/ for static Iconify icon names (icon="prefix:name") and generates
 * src/lib/icon-bundle.generated.ts, which registers just those icons via
 * addCollection() so <Icon ssr> renders them in server HTML with no pop-in.
 *
 * Icons not found here (dynamic names, missing sets) fall back to the runtime
 * Iconify API, so a stale bundle degrades to pop-in, never a broken icon.
 *
 * Run: bun run generate:icons
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { getIcons } from "@iconify/utils";
import type { IconifyInfo, IconifyJSON } from "@iconify/types";

const SRC_DIR = join(import.meta.dir, "..", "src");
const OUT_FILE = join(SRC_DIR, "lib", "icon-bundle.generated.ts");
const CREDITS_FILE = join(SRC_DIR, "lib", "icon-credits.generated.json");
// Matches JSX attributes (icon="mdi:x") and object properties (icon: "mdi:x").
// A missing set here fails the build, since these are unambiguously icons.
const ICON_CONTEXT_PATTERN = /icon[=:]\s*["']([a-z0-9-]+):([a-z0-9-]+)["']/gi;
// Matches any "set:name"-shaped string (ternaries, arrays, helper args), but
// only prefixes with an installed @iconify-json package are treated as icons,
// so lookalikes such as "og:image" never break the build.
const ICON_STRING_PATTERN = /["']([a-z0-9-]+):([a-z0-9-]+)["']/g;

function collectSourceFiles(dir: string): string[] {
  const files: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (path === OUT_FILE || /\.(test|spec)\.tsx?$/.test(entry.name)) continue;
    if (entry.isDirectory()) files.push(...collectSourceFiles(path));
    else if (/\.(ts|tsx)$/.test(entry.name)) files.push(path);
  }
  return files;
}

const installedSets = new Set(
  readdirSync(join(import.meta.dir, "..", "node_modules", "@iconify-json")),
);

const iconsByPrefix = new Map<string, Set<string>>();
function addIcon(prefix: string, name: string) {
  if (!iconsByPrefix.has(prefix)) iconsByPrefix.set(prefix, new Set());
  iconsByPrefix.get(prefix)!.add(name);
}

for (const file of collectSourceFiles(SRC_DIR)) {
  const source = readFileSync(file, "utf8");
  for (const [, prefix, name] of source.matchAll(ICON_CONTEXT_PATTERN)) {
    addIcon(prefix, name);
  }
  for (const [, prefix, name] of source.matchAll(ICON_STRING_PATTERN)) {
    if (installedSets.has(prefix)) addIcon(prefix, name);
  }
}

const collections: string[] = [];
const notices: string[] = [];
const credits: {
  prefix: string;
  name: string;
  author: IconifyInfo["author"];
  license: IconifyInfo["license"];
}[] = [];
let totalIcons = 0;
const warnings: string[] = [];

for (const prefix of [...iconsByPrefix.keys()].sort()) {
  const names = [...iconsByPrefix.get(prefix)!].sort();
  const packageDir = join(import.meta.dir, "..", "node_modules", "@iconify-json", prefix);
  let setData: IconifyJSON;
  try {
    setData = JSON.parse(
      readFileSync(join(packageDir, "icons.json"), "utf8"),
    );
  } catch {
    console.error(
      `Missing icon set "${prefix}" — run: bun add -d @iconify-json/${prefix}`,
    );
    process.exit(1);
  }

  const info: IconifyInfo = JSON.parse(readFileSync(join(packageDir, "info.json"), "utf8"));
  if (!info.name || !info.author?.name || !info.license?.title || !info.license.url) {
    throw new Error(`Missing author or license metadata for "${prefix}".`);
  }
  const noticeFile = join(import.meta.dir, "..", "public", "licenses", "icons", `${prefix}.txt`);
  if (!existsSync(noticeFile) || !readFileSync(noticeFile, "utf8").trim()) {
    throw new Error(
      `Missing license notice for "${prefix}". Preserve the upstream copyright and license notices in public/licenses/icons/${prefix}.txt once when adding this icon set.`,
    );
  }
  notices.push(readFileSync(noticeFile, "utf8"));
  credits.push({ prefix, name: info.name, author: info.author, license: info.license });

  const subset = getIcons(setData, names, true)!;
  if (subset.not_found?.length) {
    warnings.push(
      `Not in "${prefix}" set (will use runtime API): ${subset.not_found.join(", ")}`,
    );
    delete subset.not_found;
  }
  totalIcons += Object.keys(subset.icons).length;
  collections.push(`addCollection(${JSON.stringify(subset)});`);
}

const output = `// AUTO-GENERATED by scripts/generate-icon-bundle.ts — do not edit.
// Regenerate with: bun run generate:icons
// Registers every statically referenced icon so <Icon ssr> renders on the server.
import { addCollection } from "@iconify/react";

${collections.join("\n\n")}
`;

writeFileSync(OUT_FILE, output);
const previous = existsSync(CREDITS_FILE)
  ? JSON.parse(readFileSync(CREDITS_FILE, "utf8"))
  : null;
const contentHash = createHash("sha256")
  .update(JSON.stringify({ credits, notices }))
  .digest("hex");
const lastUpdated = previous?.contentHash === contentHash
  ? previous.lastUpdated
  : new Intl.DateTimeFormat("en-US", {
      month: "long",
      day: "numeric",
      year: "numeric",
      timeZone: "UTC",
    }).format(new Date());
writeFileSync(CREDITS_FILE, JSON.stringify({ lastUpdated, contentHash, credits }, null, 2) + "\n");
for (const warning of warnings) console.warn(`⚠ ${warning}`);
console.log(
  `Wrote ${OUT_FILE} — ${totalIcons} icons from ${iconsByPrefix.size} sets.`,
);
